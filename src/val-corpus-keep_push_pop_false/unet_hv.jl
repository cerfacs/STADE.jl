        ci = div(idxm1, hw) + 1
        rem = mod(idxm1, hw)
        i = div(rem, w) + 1
        j = mod(rem, w) + 1
        yi = (ci - 1) * hp1 * wp1 + ((i + pad) - 1) * wp1 + (j + pad)
        xpad0d[yi] = xpad0_stack_d[(div(n_xpad0 - 1, 1) + 1) + ((idx - 1) + 1)]
        xpad0[yi] = xpad0_stack[(div(n_xpad0 - 1, 1) + 1) + ((idx - 1) + 1)]
        xbd[idx] = xbd[idx] + xpad0bd[yi]
        xb[idx] = xb[idx] + xpad0b[yi]
        xpad0bd[yi] = 0.0
        xpad0b[yi] = 0.0
    end
    for i = n_xpad0:-1:1
        xpad0d[i] = xpad0_stack_d[(i - 1) + 1]
        xpad0[i] = xpad0_stack[(i - 1) + 1]
        xpad0bd[i] = 0.0
        xpad0b[i] = 0.0
    end
    zero_valbd = 0.0
    zero_valb = 0.0
    return nothing
end

