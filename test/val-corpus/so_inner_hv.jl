        lossd[1] = lossd[1] + (__hcse_0 + __hcse_0)
        loss[1] = loss[1] + __cse_6 * __cse_6
    end
    __ihcse_1 = max(0, div(i_n - 1, 1) + 1)
    __icse_7 = __ihcse_1
