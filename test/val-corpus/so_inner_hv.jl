    xv = 0.0
    runb = 0.0
    wvb = 0.0
    xvb = 0.0
    rund = 0.0
    runbd = 0.0
    wvd = 0.0
    wvbd = 0.0
    xvd = 0.0
    xvbd = 0.0
    rund = 0.0
    run = 0.0
    for t = 1:i_n
        for ci = 1:i_nc
            __icse_0 = div(i_nc - 1, 1) + 1
