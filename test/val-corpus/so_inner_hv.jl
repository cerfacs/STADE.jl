            __icse_19 = ((t - 1) * __icse_18 + (ci - 1)) + 1
            __icse_20 = max(0, div(i_n - 1, 1) + 1) * max(0, __icse_18) + __icse_19
            __idx_wv_stack_0 = __icse_20
            wvd = wv_stack_d[__idx_wv_stack_0]
            wv = wv_stack[__idx_wv_stack_0]
            __oldb_2d = wvbd
            __oldb_2 = wvb
            wvbd = 0.0
            wvb = 0.0
            wbd[ci + 1] = wbd[ci + 1] + __oldb_2d
