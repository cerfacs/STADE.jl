    xv_stack_d[__idx_xv_stack_7] = xvd
    xv_stack[__idx_xv_stack_7] = xv
    __icse_10 = __ihcse_1
    __idx_run_stack_0 = __icse_10 + 1
    rund = run_stack_d[__idx_run_stack_0]
    run = run_stack[__idx_run_stack_0]
    __icse_11 = __icse_10 * __ihcse_2
    __icse_12 = ((__icse_11 + __icse_11) + __icse_10) + 1
    __idx_wv_stack_2 = __icse_12
    wvd = wv_stack_d[__idx_wv_stack_2]
    wv = wv_stack[__idx_wv_stack_2]
    __idx_xv_stack_4 = __icse_12
    xvd = xv_stack_d[__idx_xv_stack_4]
    xv = xv_stack[__idx_xv_stack_4]
    for k = i_n:-1:1
        __hcse_3 = lossb[1]
        __hcse_4 = y[k]
        __cse_13d = __hcse_3 * yd[k] + __hcse_4 * lossbd[1]
        __cse_13 = __hcse_4 * __hcse_3
        ybd[k] = ybd[k] + __cse_13d
        yb[k] = yb[k] + __cse_13
        ybd[k] = ybd[k] + __cse_13d
        yb[k] = yb[k] + __cse_13
    end
    for t = i_n:-1:1
        __icse_14 = max(0, div(i_n - 1, 1) + 1) * max(0, div(i_nc - 1, 1) + 1)
        __icse_15 = (t - 1) + 1
